// Deep link from the dictionary's phonetic-family chips: phonetics.html?kanji=<kanji> opens that
// kanji's family directly, skipping the gate -- that is a lookup, not a question about where the
// visitor is. A family is listed under every level one of its members belongs to with an
// identical member array, so the first level found is as good as any other.
// ---------------------------------------------------------------------------
function findFamilyForKanji(kanji) {
    for (const level of LEVEL_META) {
        const list = QUIZ[level.key] || [];
        const i = list.findIndex(f => f.m.some(m => m.k === kanji));
        if (i >= 0) return { levelKey: level.key, index: i, family: list[i] };
    }
    return null;
}

