// As near square as the count allows: 44 shapes become 6 across and 8 down, which gives each
// tile the most room without leaving a nearly empty last row.
function columnsFor(n) { return Math.max(3, Math.floor(Math.sqrt(n))); }

function drawField() {
    const field = document.getElementById('phonetics-field');
    field.innerHTML = '';
    stageList.forEach(f => {
        const btn = document.createElement('button');
        btn.type = 'button';
        btn.className = 'tile' + metClass(f.c);
        btn.textContent = f.c;
        btn.dataset.s = quizStatus(currentLevelKey, f.c);
        btn.setAttribute('aria-label', f.c + ' — ' + window.tf('phonetics.kanjiInFamily', { n: f.m.length }));
        btn.addEventListener('click', () => openTree(f));
        field.appendChild(btn);
    });
    const counts = deckCounts();
    document.getElementById('phonetics-quick-sub').textContent =
        Math.min(ROUND, counts.all) + ' ' + window.t('drill.questions');
    layoutField();
}

// The tile size is measured, not guessed. Whatever height is left of the window after the
// title, the test bar and the legend is divided by the row count, and the width by the column
// count; the smaller wins, so the whole stage is on screen at any window size. The test bar is
// then set to exactly the width of the tiles under it.
function layoutField() {
    const view = document.getElementById('phonetics-field-view');
    if (!stageList.length || view.hidden || document.getElementById('phonetics-app').hidden) return;

    const cols = columnsFor(stageList.length);
    const rows = Math.ceil(stageList.length / cols);
    const gap = 7;

    const room = view.getBoundingClientRect();
    const quickH = document.getElementById('phonetics-quick').getBoundingClientRect().height;
    const legendH = view.querySelector('.picker-legend').getBoundingClientRect().height;
    const availH = room.height - quickH - legendH - 26;
    const availW = room.width;

    let cell = Math.min(
        (availW - (cols - 1) * gap) / cols,
        (availH - (rows - 1) * gap) / rows
    );
    cell = Math.max(26, Math.min(cell, 96));

    const field = document.getElementById('phonetics-field');
    field.style.setProperty('--cols', cols);
    field.style.setProperty('--cell', cell.toFixed(1) + 'px');
    document.getElementById('phonetics-stack').style.setProperty(
        '--fw', (cols * cell + (cols - 1) * gap).toFixed(1) + 'px');
}

