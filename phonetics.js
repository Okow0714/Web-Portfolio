function deckCounts() {
    const out = { 'new': 0, miss: 0, hit: 0, all: stageList.length };
    stageList.forEach(f => { out[quizStatus(currentLevelKey, f.c)]++; });
    return out;
}

function pool(kind) {
    if (kind === 'all') return stageList.slice();
    return stageList.filter(f => quizStatus(currentLevelKey, f.c) === kind);
}

