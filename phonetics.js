// A dial, because the five levels are a choice and not a sequence. The spokes are an SVG with
// preserveAspectRatio:none over a 0 0 100 100 viewBox and the discs are placed in percent, so
// both live in one coordinate space and stay joined at any size.
const TRAVEL_MS = 560;      // disc -> centre
const INFLATE_MS = 1000;    // the swell, before it bursts

function renderGateDial() {
    const dial = document.getElementById('phonetics-gate-dial');
    if (!dial) return;
    dial.className = 'gate-dial';
    dial.innerHTML = '';
    const NS = 'http://www.w3.org/2000/svg';
    const svg = document.createElementNS(NS, 'svg');
    svg.setAttribute('viewBox', '0 0 100 100');
    svg.setAttribute('preserveAspectRatio', 'none');
    svg.setAttribute('aria-hidden', 'true');
    dial.appendChild(svg);

    const hub = document.createElement('span');
    hub.className = 'dial-hub';
    hub.textContent = 'JLPT';
    dial.appendChild(hub);

    LEVEL_META.forEach((level, i) => {
        const a = -Math.PI / 2 + i * 2 * Math.PI / LEVEL_META.length;
        const x = 50 + 33 * Math.cos(a), y = 50 + 33 * Math.sin(a);

        const line = document.createElementNS(NS, 'line');
        line.setAttribute('x1', '50');
        line.setAttribute('y1', '50');
        line.setAttribute('x2', x.toFixed(2));
        line.setAttribute('y2', y.toFixed(2));
        line.setAttribute('class', 'dial-spoke');
        svg.appendChild(line);

        const btn = document.createElement('button');
        btn.type = 'button';
        btn.className = 'lv';
        btn.dataset.level = level.key;
        btn.style.setProperty('--hue', hueFor(level.key));
        btn.style.left = x.toFixed(2) + '%';
        btn.style.top = y.toFixed(2) + '%';
        // nav.n5Beginner already reads "N5 · Beginner" and the disc prints the key itself, so
        // the label takes only the description half.
        const desc = level.title.replace(/^\s*N\d\s*(?:·|&middot;|-)\s*/, '');
        btn.innerHTML = '<span class="lv-n">' + escapeHtml(level.key) + '</span>'
            + '<span class="lv-t">' + escapeHtml(desc) + '</span>';
        btn.setAttribute('aria-label', window.tf('phonetics.gateAria',
            { level: level.key, n: (QUIZ[level.key] || []).length }));
        btn.addEventListener('click', () => chooseLevel(level, btn));
        dial.appendChild(btn);
    });
}

function chooseLevel(level, btn) {
    const dial = document.getElementById('phonetics-gate-dial');
    const cps = CHECKPOINTS[level.key] || 1;
    dial.classList.add('away');
    dial.querySelectorAll('.lv').forEach(el => { if (el !== btn) el.classList.add('gone'); });

    btn.classList.add('travelling');
    btn.style.left = '50%';
    btn.style.top = '50%';
    document.getElementById('phonetics-gate-h').textContent = level.key + ' · ' + level.title.replace(/^\s*N\d\s*(?:·|&middot;|-)\s*/, '');
    document.getElementById('phonetics-gate-p').textContent =
        window.tf('phonetics.gateAria', { level: '', n: (QUIZ[level.key] || []).length }).replace(/^\s*—\s*/, '');

    window.setTimeout(() => {
        btn.classList.add('inflating');
        window.setTimeout(() => {
            // One stage is nothing to burst into, so N5 and N4 go straight through.
            if (cps < 2) { enterLevel(level.key, 0); return; }
            document.getElementById('phonetics-gate-p').textContent = window.t('phonetics.pickStage');
            btn.classList.add('bursting');
            window.setTimeout(() => btn.remove(), 300);
            popStages(level.key, cps);
        }, INFLATE_MS);
    }, TRAVEL_MS);
}

function popStages(levelKey, cps) {
    const dial = document.getElementById('phonetics-gate-dial');
    const all = (QUIZ[levelKey] || []).length;
    const per = Math.ceil(all / cps);
    for (let i = 0; i < cps; i++) {
        const count = Math.min(per, all - i * per);
        const chunk = levelChunks(levelKey)[i] || [];
        const done = chunk.filter(f => quizStatus(levelKey, f.c) === 'hit').length;

        let a = -Math.PI / 2 + i * 2 * Math.PI / cps;
        if (cps === 2) a = i === 0 ? Math.PI : 0;    // two read as a choice side by side, not a stack
        const x = 50 + 28 * Math.cos(a), y = 50 + 28 * Math.sin(a);

        const btn = document.createElement('button');
        btn.type = 'button';
        btn.className = 'stage';
        btn.dataset.stage = String(i + 1);
        btn.style.setProperty('--hue', hueFor(levelKey));
        btn.style.left = '50%';
        btn.style.top = '50%';
        btn.innerHTML = '<span class="stage-n">' + (i + 1) + '</span>'
            + '<span class="stage-c">' + escapeHtml(window.tf('phonetics.cpShapes', { n: count })) + '</span>'
            + '<span class="stage-bar"><i style="width:' + (count ? Math.round(100 * done / count) : 0) + '%"></i></span>';
        btn.setAttribute('aria-label', window.tf('phonetics.cpAria',
            { n: i + 1, total: cps, count, done }));
        btn.addEventListener('click', () => enterLevel(levelKey, i));
        dial.appendChild(btn);

        window.setTimeout(() => {
            btn.style.left = x.toFixed(2) + '%';
            btn.style.top = y.toFixed(2) + '%';
            btn.classList.add('out');
        }, 40 + i * 70);
    }
}

