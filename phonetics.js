// The greyed example in the answer box shows the three spellings that count. It skips any
// example that happens to BE this card's answer: an example you can copy is a free mark rather
// than a hint about the format.
const INPUT_EXAMPLES = [
    ['コウ', 'こう · kou · コウ'],
    ['シン', 'しん · shin · シン'],
    ['リョウ', 'りょう · ryou · リョウ'],
    ['カン', 'かん · kan · カン'],
    ['ジ', 'じ · ji · ジ'],
];

function inputExample(f) {
    const canon = s => (window.KANA && window.KANA.canon) ? window.KANA.canon(s) : toHira(s);
    for (const [sound, label] of INPUT_EXAMPLES) {
        if (!f.s.some(s => canon(s) === canon(sound))) return label;
    }
    return window.t('drill.hint');
}

function drawCard() {
    const card = document.getElementById('phonetics-drill-card');
    card.innerHTML = '';
    if (at >= queue.length) { drawDone(card); return; }
    const f = queue[at];

    const top = document.createElement('div');
    top.className = 'd-top';
    top.innerHTML = '<span>' + escapeHtml(deckName) + ' · ' + (at + 1) + ' / ' + queue.length + '</span>'
        + '<span><b id="d-right">' + escapeHtml(window.tf('phonetics.nRight', { n: right })) + '</b> · '
        + '<i id="d-wrong">' + escapeHtml(window.tf('phonetics.nWrong', { n: wrong })) + '</i></span>';
    const exit = document.createElement('button');
    exit.type = 'button';
    exit.className = 'd-exit';
    exit.textContent = window.t('phonetics.exitRound');
    exit.addEventListener('click', exitRound);
    top.appendChild(exit);
    card.appendChild(top);

    const meter = document.createElement('div');
    meter.className = 'd-meter';
    meter.innerHTML = '<i style="width:' + Math.round(100 * at / queue.length) + '%"></i>';
    card.appendChild(meter);

    const ask = document.createElement('p');
    ask.className = 'd-ask';
    ask.textContent = window.t('drill.ask');
    card.appendChild(ask);

    const glyph = document.createElement('div');
    glyph.className = 'd-glyph';
    glyph.textContent = f.c;
    card.appendChild(glyph);

    const form = document.createElement('form');
    form.className = 'd-form';
    const input = document.createElement('input');
    input.className = 'd-in';
    input.type = 'text';
    input.id = 'phonetics-answer';
    input.autocomplete = 'off';
    input.autocapitalize = 'off';
    input.spellcheck = false;
    input.placeholder = inputExample(f);
    input.setAttribute('aria-label', window.t('drill.inputLabel'));
    const check = document.createElement('button');
    check.type = 'submit';
    check.className = 'd-check';
    check.textContent = window.t('drill.check');
    form.appendChild(input);
    form.appendChild(check);
    card.appendChild(form);

    const hint = document.createElement('p');
    hint.className = 'd-hint';
    hint.textContent = window.t('drill.hint');
    card.appendChild(hint);

    form.addEventListener('submit', (e) => {
        e.preventDefault();
        // one handler is both Check and Next, so Enter and the button cannot advance twice
        if (answered) { at++; answered = false; drawCard(); return; }
        answered = true;
        const good = !!(window.KANA && window.KANA.matches(input.value, f.s));
        good ? right++ : wrong++;
        recordAnswer(currentLevelKey, f.c, good);
        // In place, not by redrawing: the card still holds the answer the reader is reading.
        document.getElementById('d-right').textContent = window.tf('phonetics.nRight', { n: right });
        document.getElementById('d-wrong').textContent = window.tf('phonetics.nWrong', { n: wrong });
        input.classList.add(good ? 'ok' : 'no');
        input.readOnly = true;
        check.textContent = window.t('drill.next');
        hint.textContent = window.t('drill.nextHint');
        card.appendChild(verdictFor(f, good));
        check.focus();
    });
    input.focus();
}

// The verdict carries an example word: the moment you have just tried to produce a reading is
// the moment a word that uses it is worth seeing.
function verdictFor(f, good) {
    const v = document.createElement('div');
    v.className = 'd-verdict ' + (good ? 'ok' : 'no');
    let html = '<p class="d-vh">' + escapeHtml(window.t(good ? 'drill.right' : 'drill.wrong')) + '</p>'
        + '<p class="d-va">' + escapeHtml(f.s.join('・')) + '</p>'
        + '<p class="d-vm">' + f.m.map(m =>
            '<span class="d-vk" style="--lv:' + hueFor(m.lv) + '" title="'
            + escapeHtml(m.k + ' — ' + (m.mn || '')) + '">' + escapeHtml(m.k) + '</span>').join('')
        + '</p>';

    const pick = exampleForFamily(f);
    if (pick) html += '<div class="d-ex">' + wordHtml(pick.k, pick.ex, f.s[0]) + '</div>';
    v.innerHTML = html;
    return v;
}

// Prefer a member whose word shows the sound the question was about, unchanged; then one that
// shows it with a compound's usual voicing; then any member with a checked word at all.
function exampleForFamily(f) {
    const want = toHira(f.s[0]);
    let changed = null, fallback = null;
    for (const m of f.m) {
        const ex = wordFor(m.k);
        if (!ex) continue;
        if (ex.s === want && !ex.k) return { k: m.k, ex };
        if (ex.s === want && !changed) changed = { k: m.k, ex };
        if (!fallback) fallback = { k: m.k, ex };
    }
    return changed || fallback;
}

function drawDone(card) {
    const counts = deckCounts();
    card.innerHTML = '<p class="d-score">' + right + '<small>/' + queue.length + '</small></p>'
        + '<p class="d-done">' + escapeHtml(window.tf('phonetics.roundTally', {
            hit: counts.hit, miss: counts.miss, 'new': counts['new'],
        })) + '</p>';

    const again = document.createElement('button');
    again.type = 'button';
    again.className = 'd-go';
    again.textContent = window.t('drill.again');
    again.addEventListener('click', () => { exitRound(); openDeckModal(); });
    card.appendChild(again);

    const back = document.createElement('button');
    back.type = 'button';
    back.className = 'd-go ghost';
    back.textContent = window.t('drill.toBoard');
    back.addEventListener('click', exitRound);
    card.appendChild(back);
}

