// Phonetics Family — one surface, four views.
//
//   gate   →   board   →   tree        the dictionary's ?kanji= link lands straight on a tree
//              board   →   drill       the round takes the screen; the field beside it is the
//                                      answer key, and a question you can read the answer to is
//                                      not a question
//
// The whole page runs on phonetics-quiz-data.js (~390KB). phonetics-data.js (~2.8MB) is no
// longer loaded at all: everything that reaches the screen -- shapes, their shared sounds,
// members with readings and glosses, and one checked example sentence per kanji -- is in the
// small file, generated by tools/build-phonetics-quiz.js.
//
// The argument the page makes: a phonetic component predicts a reading to TRY. The tree shows
// which members take it; the drill asks whether you can produce it. Both are the same claim.

