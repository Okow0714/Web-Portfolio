function escapeHtml(str) {
    const div = document.createElement('div');
    div.textContent = str == null ? '' : String(str);
    return div.innerHTML;
}

const toHira = s => (s || '').replace(/[ァ-ヶ]/g, c => String.fromCharCode(c.charCodeAt(0) - 0x60));

// The JLPT hues are declared once, on :root in style.css. Reading them here keeps a level the
// same colour on the dial, on its chip and on every member's level dot.
function hueFor(levelKey) {
    const v = getComputedStyle(document.documentElement)
        .getPropertyValue('--jlpt-' + String(levelKey).toLowerCase()).trim();
    return v || 'var(--border-strong)';
}

function levelChunks(levelKey) {
    const all = (QUIZ[levelKey] || []).slice();
    const n = CHECKPOINTS[levelKey] || 1;
    const per = Math.ceil(all.length / n);
    const out = [];
    for (let i = 0; i < n; i++) out.push(all.slice(i * per, (i + 1) * per));
    return out;
}

